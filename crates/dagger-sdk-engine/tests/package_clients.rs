#[derive(Clone, Copy, Debug)]
struct HostRustfmt;

impl OperationPostWork for HostRustfmt {
    async fn execute(
        &self,
        root: &OperationRoot,
        plan: &PostWorkPlan,
        _environment: &BTreeMap<String, String>,
        cancel: &Cancellation,
    ) -> Result<ProcessOutcome, EngineDiagnostic> {
        assert!(!cancel.is_cancelled());
        let PostWorkPlan::FormatRust { files, .. } = plan else {
            panic!("client rendering admits only formatter post-work")
        };
        let mut command = Command::new("rustup");
        command.args(["run", "1.99.1", "rustfmt", "--edition", "2024"]);
        for file in files {
            command.arg(root.regular_file(file).unwrap());
        }
        let output = command.output().unwrap();
        Ok(ProcessOutcome {
            success: output.status.success(),
            stdout: output.stdout,
            stderr: output.stderr,
            truncated: false,
        })
    }
}

/// One module to generate a client for.
#[derive(Clone)]
struct Client {
    name: &'static str,
    address: &'static str,
    pin: Option<&'static str>,
    schema: Vec<u8>,
}

fn greeter() -> Client {
    Client {
        name: "greeter",
        address: "/.dagger/modules/greeter",
        pin: None,
        schema: module_client_schema(GREETER_CLIENT_SCHEMA_PART),
    }
}

fn naming_app() -> Client {
    Client {
        name: "naming-app",
        address: "github.com/example/modules/naming-app@v1.2.0",
        pin: Some(PIN),
        schema: module_client_schema(NAMING_APP_CLIENT_SCHEMA_PART),
    }
}

/// A workspace with one Cargo package, `app`, as the engine adapter mounts it.
struct Package {
    temporary: tempfile::TempDir,
}

impl Package {
    fn new(manifest: &str) -> Self {
        let package = Self::bare();
        package.write("Cargo.toml", manifest);
        package.write("src/main.rs", "mod dagger_clients;\n\nfn main() {}\n");
        package
    }

    fn bare() -> Self {
        let temporary = tempfile::tempdir().unwrap();
        fs::create_dir_all(temporary.path().join("project").join(PACKAGE)).unwrap();
        fs::create_dir_all(temporary.path().join("schemas")).unwrap();
        Self { temporary }
    }

    fn project(&self) -> PathBuf {
        self.temporary.path().join("project")
    }

    fn root(&self) -> PathBuf {
        self.project().join(PACKAGE)
    }

    fn write(&self, path: &str, contents: impl AsRef<[u8]>) {
        let destination = self.root().join(path);
        fs::create_dir_all(destination.parent().unwrap()).unwrap();
        fs::write(destination, contents).unwrap();
    }

    fn read(&self, path: &str) -> String {
        fs::read_to_string(self.root().join(path)).unwrap()
    }

    fn exists(&self, path: &str) -> bool {
        self.root().join(path).exists()
    }

    /// Runs the operation for `clients`, mounting each schema as the adapter does.
    async fn generate(&self, clients: &[Client]) -> Result<ExecutionResult, EngineDiagnostic> {
        self.generate_request(request(self.schemas(clients))).await
    }

    fn schemas(&self, clients: &[Client]) -> Vec<PackageClientInput> {
        let schemas = self.temporary.path().join("schemas");
        clients
            .iter()
            .enumerate()
            .map(|(index, client)| {
                let name = format!("{index}.json");
                fs::write(schemas.join(&name), &client.schema).unwrap();
                PackageClientInput {
                    name: StableCoordinate::new(client.name).unwrap(),
                    address: StableCoordinate::new(client.address).unwrap(),
                    pin: client.pin.map(|pin| FullRevision::new(pin).unwrap()),
                    schema: SchemaInput {
                        path: path(&name),
                        digest: hash(&client.schema),
                    },
                }
            })
            .collect()
    }

    async fn generate_request(
        &self,
        request: PackageClientsRequest,
    ) -> Result<ExecutionResult, EngineDiagnostic> {
        execute_package_clients_with_post_work(
            &OperationRoot::open(self.project()).unwrap(),
            &OperationRoot::open(self.temporary.path().join("schemas")).unwrap(),
            &request,
            &descriptor(),
            &Cancellation::default(),
            &HostRustfmt,
        )
        .await
    }

    /// Every file of the workspace, by path from the package.
    fn snapshot(&self) -> BTreeMap<String, Vec<u8>> {
        fn visit(root: &Path, at: &Path, output: &mut BTreeMap<String, Vec<u8>>) {
            for entry in fs::read_dir(at).unwrap() {
                let entry = entry.unwrap();
                let kind = entry.file_type().unwrap();
                let name = |path: &Path| {
                    path.strip_prefix(root)
                        .unwrap()
                        .to_string_lossy()
                        .replace('\\', "/")
                };
                if kind.is_dir() {
                    visit(root, &entry.path(), output);
                } else if kind.is_symlink() {
                    output.insert(
                        name(&entry.path()),
                        fs::read_link(entry.path())
                            .unwrap()
                            .to_string_lossy()
                            .into_owned()
                            .into_bytes(),
                    );
                } else {
                    output.insert(
                        entry
                            .path()
                            .strip_prefix(root)
                            .unwrap()
                            .to_string_lossy()
                            .replace('\\', "/"),
                        fs::read(entry.path()).unwrap(),
                    );
                }
            }
        }
        let mut output = BTreeMap::new();
        visit(&self.project(), &self.project(), &mut output);
        output
    }
}

fn request(clients: Vec<PackageClientInput>) -> PackageClientsRequest {
    PackageClientsRequest {
        format_version: FormatVersion,
        target: target(),
        sdk_dependency: dependency(),
        client_root: path(PACKAGE),
        clients,
    }
}

fn descriptor() -> EngineSourceDescriptor {
    let target = target();
    EngineSourceDescriptor {
        format_version: FormatVersion,
        repository: target.repository,
        dagger_revision: target.dagger_revision,
        engine_version: target.engine_version,
        rust_sdk_version: target.rust_sdk_version,
        rust_toolchain: target.rust_toolchain,
        sdk_dependency: dependency(),
        core_schema_digest: target.core_schema_digest,
        packaged_asset_manifest_digest: hash(b"package clients fixture"),
    }
}

fn target() -> TargetIdentity {
    TargetIdentity {
        format_version: FormatVersion,
        repository: CanonicalRepositoryUrl::new("https://github.com/dagger/dagger").unwrap(),
        dagger_revision: FullRevision::new(REVISION).unwrap(),
        engine_version: ExactVersion::new("1.0.0-beta.27").unwrap(),
        rust_sdk_version: ExactVersion::new("0.9.0").unwrap(),
        rust_toolchain: ExactRustToolchain::new("1.99.1").unwrap(),
        core_schema_digest: Sha256Digest::new(CORE_SCHEMA_DIGEST).unwrap(),
    }
}

fn dependency() -> PublishedSdkDependency {
    PublishedSdkDependency::Registry {
        registry: CanonicalRegistry::new("crates-io").unwrap(),
        package: SdkPackageName::new("tokeira-dagger-sdk").unwrap(),
        exact_version: ExactVersion::new("0.9.0").unwrap(),
    }
}

fn path(value: &str) -> RelativeOperationPath {
    RelativeOperationPath::parse(value).unwrap()
}

fn hash(bytes: &[u8]) -> Sha256Digest {
    Sha256Digest::new(format!("sha256:{:x}", Sha256::digest(bytes))).unwrap()
}

/// The paths of a result, from the package.
fn from_package<'a>(paths: impl IntoIterator<Item = &'a RelativeOperationPath>) -> Vec<String> {
    paths
        .into_iter()
        .map(|path| {
            path.as_str()
                .strip_prefix(&format!("{PACKAGE}/"))
                .expect("a result path lies in the package")
                .to_owned()
        })
        .collect()
}

// The engine adapter is written in Go and builds the request as plain data. Its test
// checks that it writes this document byte for byte; this one, that the document is
// the request model, and that a result is the document the adapter's decoder is
// tested with.
#[test]
fn the_adapters_documents_are_the_request_and_result_models() {
    let document = include_bytes!("fixtures/package-clients-request.json");
    let decoded: EngineExecutionRequest = decode_canonical(document).unwrap();
    let digest =
        |digit: char| Sha256Digest::new(format!("sha256:{}", digit.to_string().repeat(64)));
    let mut expected = request(vec![
        PackageClientInput {
            name: StableCoordinate::new("greeter").unwrap(),
            address: StableCoordinate::new("/.dagger/modules/greeter").unwrap(),
            pin: None,
            schema: SchemaInput {
                path: path("0.json"),
                digest: digest('1').unwrap(),
            },
        },
        PackageClientInput {
            name: StableCoordinate::new("naming-app").unwrap(),
            address: StableCoordinate::new("github.com/example/modules/naming-app@v1.2.0").unwrap(),
            pin: Some(FullRevision::new(PIN).unwrap()),
            schema: SchemaInput {
                path: path("1.json"),
                digest: digest('2').unwrap(),
            },
        },
    ]);
    expected.client_root = path("workspace/services/app");
    let expected = EngineExecutionRequest::GeneratePackageClients(expected);
    assert_eq!(decoded, expected);
    assert_eq!(canonical_bytes(&expected).unwrap(), document);

    let result = ExecutionResult {
        format_version: FormatVersion,
        kind: ExecutionResultKind::PackageClients,
        output_root: path("workspace/services/app"),
        touched_paths: [
            path("workspace/services/app/Cargo.toml"),
            path("workspace/services/app/src/dagger_clients/mod.rs"),
        ]
        .into(),
        removed_paths: [path(
            "workspace/services/app/src/dagger_clients/greeter/greeter.rs",
        )]
        .into(),
        operation_manifest: None,
        vcs_generated: Default::default(),
        vcs_ignored: Default::default(),
    };
    assert_eq!(
        String::from_utf8(canonical_bytes(&result).unwrap()).unwrap(),
        include_str!("fixtures/package-clients-result.json")
    );
}

// The private command takes one schema for an operation on one module, and a
// directory of them for a package's clients. Neither is accepted in the other's place.
#[tokio::test]
async fn the_command_takes_a_schema_directory_for_package_clients_alone() {
    let package = Package::bare();
    let control = package.temporary.path();
    let write = |name: &str, bytes: Vec<u8>| {
        fs::write(control.join(name), bytes).unwrap();
        control.join(name).to_string_lossy().into_owned()
    };
    let clients = write(
        "clients.json",
        canonical_bytes(&EngineExecutionRequest::GeneratePackageClients(request(
            Vec::new(),
        )))
        .unwrap(),
    );
    let initialize = write(
        "initialize.json",
        canonical_bytes(&EngineExecutionRequest::InitializeModule(
            InitializationRequest {
                format_version: FormatVersion,
                target: target(),
                module: ModuleOperationInput {
                    name: StableCoordinate::new("app").unwrap(),
                    original_name: StableCoordinate::new("app").unwrap(),
                    source_subpath: path(PACKAGE),
                    config_format: ModuleConfigFormat::Current,
                    source_digest: hash(b"app"),
                    resolved_pin: None,
                },
                package_name: StableCoordinate::new("app").unwrap(),
                sdk_dependency: dependency(),
            },
        ))
        .unwrap(),
    );
    let descriptor = write("descriptor.json", canonical_bytes(&descriptor()).unwrap());
    let schema = write("schema.json", b"{}".to_vec());
    let project = package.project().to_string_lossy().into_owned();
    let schemas = control.join("schemas").to_string_lossy().into_owned();
    let result = control.join("result.json").to_string_lossy().into_owned();
    let run = |request: &str, extra: &[&str]| {
        let mut arguments = vec![
            "dagger-rust-engine".to_owned(),
            "execute".to_owned(),
            "--request".to_owned(),
            request.to_owned(),
            "--descriptor".to_owned(),
            descriptor.clone(),
            "--project".to_owned(),
            project.clone(),
            "--result".to_owned(),
            result.clone(),
        ];
        arguments.extend(extra.iter().map(|argument| (*argument).to_owned()));
        dagger_sdk_engine::cli::run_from(arguments)
    };

    let before = package.snapshot();
    let error = run(&clients, &[]).await.unwrap_err();
    assert_eq!(error.coordinate.as_deref(), Some("schemas"));
    let error = run(&clients, &["--schema", &schema]).await.unwrap_err();
    assert_eq!(error.coordinate.as_deref(), Some("schemas"));
    let error = run(&clients, &["--schemas", &schemas, "--schema", &schema])
        .await
        .unwrap_err();
    assert_eq!(error.coordinate.as_deref(), Some("schema"));
    let error = run(&initialize, &["--schemas", &schemas])
        .await
        .unwrap_err();
    assert_eq!(error.coordinate.as_deref(), Some("schemas"));
    assert_eq!(error.code, EngineDiagnosticCode::OperationInputInvalid);
    assert!(!Path::new(&result).exists());
    assert_eq!(package.snapshot(), before);

    run(&clients, &["--schemas", &schemas]).await.unwrap();
    let written: ExecutionResult = decode_canonical(&fs::read(&result).unwrap()).unwrap();
    assert_eq!(written.kind, ExecutionResultKind::PackageClients);
    assert!(written.touched_paths.is_empty() && written.removed_paths.is_empty());
}

// The whole layout, the manifest edit, and idempotence: the same clients generated
// again write and remove nothing.
#[tokio::test]
async fn a_package_gains_its_clients_and_a_second_run_changes_nothing() {
    let package = Package::new(&format!("{MANIFEST}\n[dependencies]\nserde = \"1\"\n"));
    package.write("Cargo.lock", "# the author's lockfile\n");
    let clients = [naming_app(), greeter()];

    let result = package.generate(&clients).await.unwrap();
    assert_eq!(result.kind, ExecutionResultKind::PackageClients);
    assert_eq!(result.output_root.as_str(), PACKAGE);
    assert!(result.removed_paths.is_empty());
    assert!(result.operation_manifest.is_none());
    let touched = from_package(&result.touched_paths);
    for expected in [
        "Cargo.toml",
        "src/dagger_clients/.dagger-generated.json",
        "src/dagger_clients/mod.rs",
        "src/dagger_clients/greeter/.dagger-generated.json",
        "src/dagger_clients/greeter/mod.rs",
        "src/dagger_clients/greeter/greeter.rs",
        "src/dagger_clients/greeter/greeter_message.rs",
        "src/dagger_clients/naming_app/.dagger-generated.json",
        "src/dagger_clients/naming_app/mod.rs",
        "src/dagger_clients/naming_app/naming_app_http_fetcher.rs",
    ] {
        assert!(
            touched.iter().any(|path| path == expected),
            "{expected}: {touched:?}"
        );
    }
    // Everything written is in the package's manifest or its clients directory.
    assert!(
        touched
            .iter()
            .all(|path| path == "Cargo.toml" || path.starts_with("src/dagger_clients/")),
        "{touched:?}"
    );

    assert_eq!(
        package.read("Cargo.toml"),
        format!("{MANIFEST}\n[dependencies]\nserde = \"1\"\n{SDK_DEPENDENCY}")
    );
    assert_eq!(package.read("Cargo.lock"), "# the author's lockfile\n");
    assert_eq!(
        package.read("src/main.rs"),
        "mod dagger_clients;\n\nfn main() {}\n"
    );
    assert_eq!(package.read("src/dagger_clients/mod.rs"), AGGREGATOR);

    // Each client serves its module from the address and pin of its request, and
    // every generated file begins with the marker its record recognises it by.
    let greeter_index = package.read("src/dagger_clients/greeter/mod.rs");
    assert!(greeter_index.contains("\"/.dagger/modules/greeter\""));
    let naming_index = package.read("src/dagger_clients/naming_app/mod.rs");
    assert!(naming_index.contains("\"github.com/example/modules/naming-app@v1.2.0\""));
    assert!(naming_index.contains(&format!("\"{PIN}\"")));
    for (path, bytes) in package.snapshot() {
        if path.contains("/dagger_clients/") && path.ends_with(".rs") {
            assert!(bytes.starts_with(b"// @generated"), "{path}");
        }
    }

    // A record lists exactly the generated files beside it, with the SHA-256 of the
    // formatted bytes, and never itself.
    let record: serde_json::Value =
        serde_json::from_str(&package.read("src/dagger_clients/greeter/.dagger-generated.json"))
            .unwrap();
    assert_eq!(record["version"], 1);
    let recorded = record["files"].as_object().unwrap();
    let mut on_disk = fs::read_dir(package.root().join("src/dagger_clients/greeter"))
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .filter(|name| name != ".dagger-generated.json")
        .collect::<Vec<_>>();
    on_disk.sort();
    assert_eq!(recorded.keys().cloned().collect::<Vec<_>>(), on_disk);
    for (name, digest) in recorded {
        let bytes = fs::read(package.root().join("src/dagger_clients/greeter").join(name)).unwrap();
        assert_eq!(
            digest.as_str().unwrap(),
            format!("{:x}", Sha256::digest(&bytes))
        );
    }
    assert_eq!(
        package.read("src/dagger_clients/.dagger-generated.json"),
        format!(
            "{{\n  \"version\": 1,\n  \"files\": {{\n    \"mod.rs\": \"{:x}\"\n  }}\n}}\n",
            Sha256::digest(AGGREGATOR.as_bytes())
        )
    );

    let generated = package.snapshot();
    let again = package.generate(&clients).await.unwrap();
    assert!(again.touched_paths.is_empty(), "{:?}", again.touched_paths);
    assert!(again.removed_paths.is_empty());
    assert_eq!(package.snapshot(), generated);
    // Nor does the order the engine lists the clients in matter.
    let reordered = package.generate(&[greeter(), naming_app()]).await.unwrap();
    assert!(reordered.touched_paths.is_empty());
}

// `dagger module client rm`: the client's unchanged files go, an edited one stays,
// its record is kept, emptied, and `mod.rs` no longer declares it. With the last
// client gone `mod.rs` goes too, and the manifest is not edited again.
#[tokio::test]
async fn a_removed_client_is_pruned_and_what_its_author_edited_stays() {
    let package = Package::new(MANIFEST);
    package.generate(&[greeter(), naming_app()]).await.unwrap();
    let edited = format!(
        "{}// edited\n",
        package.read("src/dagger_clients/greeter/greeter_message.rs")
    );
    package.write("src/dagger_clients/greeter/greeter_message.rs", &edited);
    package.write("src/dagger_clients/greeter/notes.md", "mine\n");

    let result = package.generate(&[naming_app()]).await.unwrap();
    let removed = from_package(&result.removed_paths);
    assert!(removed.contains(&"src/dagger_clients/greeter/mod.rs".to_owned()));
    assert!(removed.contains(&"src/dagger_clients/greeter/greeter.rs".to_owned()));
    assert!(
        removed
            .iter()
            .all(|path| path.starts_with("src/dagger_clients/greeter/"))
    );
    assert!(
        !removed
            .iter()
            .any(|path| path.ends_with("greeter_message.rs"))
    );
    assert_eq!(
        from_package(&result.touched_paths),
        [
            "src/dagger_clients/.dagger-generated.json",
            "src/dagger_clients/greeter/.dagger-generated.json",
            "src/dagger_clients/mod.rs",
        ]
    );
    assert!(!package.exists("src/dagger_clients/greeter/mod.rs"));
    assert_eq!(
        package.read("src/dagger_clients/greeter/greeter_message.rs"),
        edited
    );
    assert_eq!(
        package.read("src/dagger_clients/greeter/notes.md"),
        "mine\n"
    );
    assert_eq!(
        package.read("src/dagger_clients/greeter/.dagger-generated.json"),
        EMPTY_RECORD
    );
    assert_eq!(
        package.read("src/dagger_clients/mod.rs"),
        AGGREGATOR.replace("#[rustfmt::skip]\npub mod greeter;\n\n", "")
    );
    assert!(package.exists("src/dagger_clients/naming_app/mod.rs"));
    let again = package.generate(&[naming_app()]).await.unwrap();
    assert!(again.touched_paths.is_empty() && again.removed_paths.is_empty());

    // The last client: a manifest that no longer states the release is left alone,
    // since no client is generated.
    let stale = package.read("Cargo.toml").replace("=0.9.0", "=0.7.1");
    package.write("Cargo.toml", &stale);
    let result = package.generate(&[]).await.unwrap();
    assert!(from_package(&result.removed_paths).contains(&"src/dagger_clients/mod.rs".to_owned()));
    assert_eq!(
        from_package(&result.touched_paths),
        [
            "src/dagger_clients/.dagger-generated.json",
            "src/dagger_clients/naming_app/.dagger-generated.json",
        ]
    );
    assert!(!package.exists("src/dagger_clients/mod.rs"));
    assert_eq!(
        package.read("src/dagger_clients/.dagger-generated.json"),
        EMPTY_RECORD
    );
    assert_eq!(package.read("Cargo.toml"), stale);
    let again = package.generate(&[]).await.unwrap();
    assert!(again.touched_paths.is_empty() && again.removed_paths.is_empty());

    // A client added back takes its directory again. The emptied record no longer
    // lists the edited file, which still begins with the generated marker, so it is
    // replaced: Go's rule for a generated file that no record lists.
    package.generate(&[greeter()]).await.unwrap();
    assert_ne!(
        package.read("src/dagger_clients/greeter/greeter_message.rs"),
        edited
    );
    assert_eq!(
        package.read("src/dagger_clients/greeter/notes.md"),
        "mine\n"
    );
}

