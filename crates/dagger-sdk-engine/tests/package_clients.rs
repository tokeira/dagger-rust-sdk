// Two modules whose names make one Rust module cannot both be clients, and the
// refusal names both. A keyword is a module name with `r#`, in a directory without,
// except `mod`, which would meet the clients' own `mod.rs`.
#[tokio::test]
async fn clients_are_named_as_rust_modules() {
    let package = Package::new(MANIFEST);
    let before = package.snapshot();
    let error = package
        .generate(&[
            Client {
                name: "engine-dev",
                ..greeter()
            },
            Client {
                name: "EngineDev",
                ..naming_app()
            },
        ])
        .await
        .unwrap_err();
    assert_eq!(error.code, EngineDiagnosticCode::OperationInputInvalid);
    assert_eq!(
        error.message,
        "modules `engine-dev` and `EngineDev` would both be the Rust module `engine_dev`; a package can have a client for only one of them"
    );
    let error = package
        .generate(&[Client {
            name: "--",
            ..greeter()
        }])
        .await
        .unwrap_err();
    assert!(
        error
            .message
            .starts_with("module `--` has no name a Rust module can take")
    );
    for name in ["mod", "Mod"] {
        let error = package
            .generate(&[Client { name, ..greeter() }])
            .await
            .unwrap_err();
        assert_eq!(error.code, EngineDiagnosticCode::OperationInputInvalid);
        assert_eq!(
            error.message,
            format!(
                "module `{name}` would be the Rust module `mod`, which Rust would look for in both src/dagger_clients/mod.rs and src/dagger_clients/mod/mod.rs; no client can be generated for it"
            )
        );
    }
    assert_eq!(package.snapshot(), before);

    package
        .generate(&[
            Client {
                name: "gen",
                ..greeter()
            },
            Client {
                name: "a10",
                ..greeter()
            },
            Client {
                name: "a2",
                ..greeter()
            },
            Client {
                name: "engine-dev",
                ..naming_app()
            },
        ])
        .await
        .unwrap();
    assert_eq!(
        package.read("src/dagger_clients/mod.rs"),
        "// @generated by `dagger generate`. Do not edit.\n//! Typed clients for Dagger modules.\n\n#[rustfmt::skip]\npub mod a_10;\n\n#[rustfmt::skip]\npub mod a_2;\n\n#[rustfmt::skip]\npub mod engine_dev;\n\n#[rustfmt::skip]\npub mod r#gen;\n"
    );
    assert!(package.exists("src/dagger_clients/gen/mod.rs"));
    assert!(package.exists("src/dagger_clients/engine_dev/mod.rs"));
}

