// Every check comes before the first write. Here the manifest needs the dependency,
// one client is new, and the other has a file its author edited: nothing is written.
#[tokio::test]
async fn an_edited_file_refuses_generation_with_nothing_written() {
    let package = Package::new(MANIFEST);
    package.generate(&[greeter()]).await.unwrap();
    let edited = package
        .read("src/dagger_clients/greeter/mod.rs")
        .replace("pub struct Client", "pub struct Client // mine\n");
    package.write("src/dagger_clients/greeter/mod.rs", &edited);
    package.write("Cargo.toml", MANIFEST);
    let before = package.snapshot();

    // The module moved, so its client's `mod.rs` must change.
    let moved = Client {
        address: "/modules/greeter",
        ..greeter()
    };
    let error = package.generate(&[moved, naming_app()]).await.unwrap_err();
    assert_eq!(error.code, EngineDiagnosticCode::OwnershipConflict);
    assert_eq!(
        error.message,
        "src/dagger_clients/greeter/mod.rs contains user changes; refusing to overwrite it"
    );
    assert_eq!(
        error.coordinate.as_deref(),
        Some("workspace/app/src/dagger_clients/greeter/mod.rs")
    );
    assert_eq!(package.snapshot(), before);

    // Deleting the edited file lets generation write it again.
    fs::remove_file(package.root().join("src/dagger_clients/greeter/mod.rs")).unwrap();
    let result = package.generate(&[greeter()]).await.unwrap();
    assert!(
        from_package(&result.touched_paths)
            .contains(&"src/dagger_clients/greeter/mod.rs".to_owned())
    );
}

