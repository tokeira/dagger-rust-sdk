// The dependency a package inherits is its workspace's to state. The workspace
// manifest is found in a directory above the package, and is never written.
#[tokio::test]
async fn an_inherited_sdk_dependency_must_state_the_release_in_its_workspace() {
    let member = format!("{MANIFEST}\n[dependencies]\nsdk = {{ workspace = true }}\n");
    let workspace = |version: &str| {
        format!(
            "[workspace]\nmembers = [\"app\"]\n\n[workspace.dependencies]\nsdk = {{ package = \"tokeira-dagger-sdk\", version = \"{version}\" }}\n"
        )
    };

    let package = Package::new(&member);
    package.write("../Cargo.toml", workspace("0.9"));
    let before = package.snapshot();
    let error = package.generate(&[greeter()]).await.unwrap_err();
    assert_eq!(error.code, EngineDiagnosticCode::SdkDependencyConflict);
    assert_eq!(error.coordinate.as_deref(), Some("workspace/Cargo.toml"));
    assert_eq!(
        error.message,
        "the package inherits `sdk` from its Cargo workspace, which does not state the SDK release these clients are generated for; write `sdk = { package = \"tokeira-dagger-sdk\", version = \"=0.9.0\" }` under [workspace.dependencies] in ../Cargo.toml"
    );
    assert_eq!(package.snapshot(), before);

    package.write("../Cargo.toml", workspace("=0.9.0"));
    let result = package.generate(&[greeter()]).await.unwrap();
    assert!(
        from_package(&result.touched_paths)
            .iter()
            .all(|path| path.starts_with("src/dagger_clients/"))
    );
    assert_eq!(package.read("Cargo.toml"), member);
    assert_eq!(package.read("../Cargo.toml"), workspace("=0.9.0"));
    // The client reaches the SDK by the package's own name for it.
    assert!(
        package
            .read("src/dagger_clients/greeter/mod.rs")
            .contains("sdk::Client")
    );
}

// What an author's own checks make of generated clients. The package is a binary
// with a private `mod dagger_clients;` that calls part of one client and none of
// the other, formats with its own rustfmt configuration, and adds no configuration
// for the generated code. From its root, `cargo fmt --check` and
// `cargo clippy --all-targets -- -D warnings` pass, in each edition.
#[tokio::test]
async fn generated_clients_pass_their_authors_format_and_lint_checks() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let crates = manifest_dir.parent().unwrap();
    let workspace = crates.parent().unwrap();
    let holder = tempfile::tempdir().unwrap();
    let target_dir = holder.path().join("target");

    for edition in ["2021", "2024"] {
        let package = Package::new(&format!(
            "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"{edition}\"\n"
        ));
        package.write("rustfmt.toml", "hard_tabs = true\nmax_width = 60\n");
        package.write(
            "src/main.rs",
            "mod dagger_clients;\n\nuse dagger_clients::greeter;\n\nasync fn calls() -> Result<(), Box<dyn std::error::Error>> {\n\tlet client = dagger_sdk::connect().await?;\n\tlet answer = greeter::Client::new(&client)\n\t\t.greeter()\n\t\t.hello(\"Ian\")\n\t\t.await?;\n\tprintln!(\"{answer}\");\n\tOk(())\n}\n\nfn main() {\n\tlet _calls = calls();\n}\n",
        );
        // Generated twice, with a client added the second time, as an author does.
        package.generate(&[greeter()]).await.unwrap();
        package.generate(&[greeter(), naming_app()]).await.unwrap();

        // The clients' release is not published from this checkout, so the package
        // takes it from here, and with it the checkout's locked dependency versions.
        // Neither touches a generated file or the dependency generation wrote.
        let manifest = package.read("Cargo.toml");
        assert!(manifest.ends_with(SDK_DEPENDENCY), "{manifest}");
        package.write(
            "Cargo.toml",
            format!(
                "{manifest}\n[workspace]\n\n[patch.crates-io]\ntokeira-dagger-sdk = {{ path = {:?} }}\n",
                crates.join("dagger-sdk")
            ),
        );
        fs::copy(
            workspace.join("Cargo.lock"),
            package.root().join("Cargo.lock"),
        )
        .unwrap();

        let format = Command::new(env!("CARGO"))
            .args(["fmt", "--check"])
            .current_dir(package.root())
            .output()
            .unwrap();
        assert!(
            format.status.success(),
            "edition {edition}: cargo fmt --check fails on a package with generated clients:\n{}{}",
            String::from_utf8_lossy(&format.stdout),
            String::from_utf8_lossy(&format.stderr)
        );
        let lints = Command::new(env!("CARGO"))
            .args([
                "clippy",
                "--all-targets",
                "--offline",
                "--quiet",
                "--",
                "-D",
                "warnings",
            ])
            .env("CARGO_TARGET_DIR", &target_dir)
            .current_dir(package.root())
            .output()
            .unwrap();
        assert!(
            lints.status.success(),
            "edition {edition}: cargo clippy fails on a package with generated clients:\n{}",
            String::from_utf8_lossy(&lints.stderr)
        );
    }
}

// rustfmt neither formats the files of a client declared with `#[rustfmt::skip]` nor
// reorders such declarations. Both are checked on a package whose client files are
// far from formatted and whose declarations rustfmt would otherwise sort, under the
// style of each edition.
#[test]
fn rustfmt_leaves_declared_clients_and_their_order_alone() {
    let temporary = tempfile::tempdir().unwrap();
    let root = temporary.path();
    fs::create_dir_all(root.join("src/dagger_clients")).unwrap();
    fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
    )
    .unwrap();
    fs::write(
        root.join("src/main.rs"),
        "mod dagger_clients;\n\nfn main() {}\n",
    )
    .unwrap();
    let names = ["b", "a10", "a2", "r#gen"];
    for name in names {
        let directory = root
            .join("src/dagger_clients")
            .join(name.trim_start_matches("r#"));
        fs::create_dir_all(&directory).unwrap();
        fs::write(
            directory.join("mod.rs"),
            "// @generated\npub   fn   f( ){let x=1;let _=x;}\n",
        )
        .unwrap();
    }
    let check = |skip: bool, style: &str| {
        let mut index = String::from("// @generated\n");
        for name in names {
            if skip {
                index.push_str("\n#[rustfmt::skip]");
            }
            index.push_str(&format!("\npub mod {name};\n"));
        }
        fs::write(root.join("src/dagger_clients/mod.rs"), index).unwrap();
        fs::write(
            root.join("rustfmt.toml"),
            format!("style_edition = \"{style}\"\nhard_tabs = true\n"),
        )
        .unwrap();
        Command::new(env!("CARGO"))
            .args(["fmt", "--check"])
            .current_dir(root)
            .output()
            .unwrap()
    };
    for style in ["2015", "2021", "2024"] {
        let skipped = check(true, style);
        assert!(
            skipped.status.success(),
            "style {style}:\n{}",
            String::from_utf8_lossy(&skipped.stdout)
        );
        // Without the attribute rustfmt does reach the files, so the check above
        // is not passing for want of looking.
        let reached = check(false, style);
        assert!(!reached.status.success(), "style {style}");
        assert!(String::from_utf8_lossy(&reached.stdout).contains("dagger_clients/a10/mod.rs"));
    }
}
